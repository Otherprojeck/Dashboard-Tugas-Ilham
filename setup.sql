-- Fitur penghapusan/admin belum diaktifkan. Tambahkan Supabase Auth dan policy admin sebelum
-- memberi wewenang menghapus dokumen.

create table if not exists public.documents (
  id bigint generated by default as identity primary key,
  jenis text not null check (jenis in ('Tugas Mahasiswa', 'Materi Perkuliahan')),
  nama text not null check (char_length(nama) between 1 and 100),
  nim text not null check (char_length(nim) between 1 and 40),
  judul text not null check (char_length(judul) between 1 and 150),
  deskripsi text not null default '' check (char_length(deskripsi) <= 1500),
  file_name text not null check (char_length(file_name) <= 255),
  file_path text not null unique check (char_length(file_path) <= 255),
  created_at timestamptz not null default now()
);

alter table public.documents enable row level security;

drop policy if exists "Public can read documents" on public.documents;
create policy "Public can read documents"
on public.documents for select to anon, authenticated
using (true);

drop policy if exists "Public can submit documents" on public.documents;
create policy "Public can submit documents"
on public.documents for insert to anon, authenticated
with check (
  jenis in ('Tugas Mahasiswa', 'Materi Perkuliahan')
  and char_length(nama) between 1 and 100
  and char_length(nim) between 1 and 40
  and char_length(judul) between 1 and 150
  and char_length(deskripsi) <= 1500
  and char_length(file_name) <= 255
  and char_length(file_path) <= 255
);

-- Storage bucket untuk file PDF, maksimal 10 MB per file.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('kampushub-pdf', 'kampushub-pdf', true, 10485760, array['application/pdf'])
on conflict (id) do update
set public = true,
    file_size_limit = 10485760,
    allowed_mime_types = array['application/pdf'];

drop policy if exists "Public can upload KampusHub PDFs" on storage.objects;
create policy "Public can upload KampusHub PDFs"
on storage.objects for insert to anon, authenticated
with check (
  bucket_id = 'kampushub-pdf'
  and lower(name) like '%.pdf'
);

drop policy if exists "Public can read KampusHub PDFs" on storage.objects;
create policy "Public can read KampusHub PDFs"
on storage.objects for select to anon, authenticated
using (bucket_id = 'kampushub-pdf');

